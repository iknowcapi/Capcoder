def _readme(name: str, tagline: str, run_lines: list[str]) -> str:
    runs = "\n".join(f"   {ln}" for ln in run_lines)
    return f"""# {name}

> {tagline}

Generated by RECURSIVE.BBS.

## Run it

```bash
{runs}
```

Open http://localhost:8000 in your browser.

## Structure

- `backend/server.py` — FastAPI app, in-memory storage (swap to MongoDB later)
- `backend/requirements.txt` — Python deps
- `frontend/index.html` — single-page UI (vanilla JS, no build step)
- `run.sh` — one-shot installer + launcher

## Endpoints

See the OpenAPI docs at http://localhost:8000/docs once running.
"""


def _requirements_txt() -> str:
    return "fastapi==0.115.0\nuvicorn[standard]==0.30.6\npydantic==2.9.2\n"


def _run_sh() -> str:
    return """#!/usr/bin/env bash
set -e
cd "$(dirname "$0")"
python3 -m venv .venv 2>/dev/null || true
source .venv/bin/activate
pip install -q -r backend/requirements.txt
cd backend
exec uvicorn server:app --host 0.0.0.0 --port 8000
"""


