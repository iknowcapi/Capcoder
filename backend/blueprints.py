"""
Code-builder blueprints. Each blueprint IS a code-building bot:
given a (prompt, name) it emits a folder of real, runnable files.

Output shape (per blueprint):
{
  "bot": {                       # the bot that builds this app
    "name": str,
    "domain": str,
    "recipe": [str],             # ordered steps the bot performs
    "templates": [str],          # file paths the bot owns
  },
  "app": {                       # the produced app
    "name": str,
    "version": "0.1.0",
    "tagline": str,
    "entities": [{"name": str, "fields": [{"name": str, "type": str}]}],
    "endpoints": [{"method": str, "path": str, "purpose": str}],
    "stack": [str],
  },
  "files": [{"path": str, "content": str}],
}
"""
from __future__ import annotations

import hashlib
import re
from typing import Callable


def _slug(text: str, fallback: str = "app") -> str:
    s = re.sub(r"[^a-zA-Z0-9]+", "-", text.strip().lower()).strip("-")
    return s or fallback


def _name_from_prompt(prompt: str, fallback: str = "app") -> str:
    toks = re.findall(r"[A-Za-z]+", prompt)
    return ("".join(t.capitalize() for t in toks[:3]) or fallback) or fallback


