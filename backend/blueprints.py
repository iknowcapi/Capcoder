def detect_domain(prompt: str) -> str:
    p = " " + prompt.lower() + " "
    for domain, kws in _KEYWORDS:
        for kw in kws:
            if kw in p:
                return domain
    return "generic-crud"


def build_project(prompt: str, exemplars: list[dict] | None = None) -> dict:
    domain = detect_domain(prompt)
    fn = BLUEPRINTS[domain]
    proj = fn(prompt)
    proj["bot"]["dna_signature"] = "0x" + hashlib.md5((domain + prompt).encode()).hexdigest()[:8]
    if exemplars:
        top = exemplars[0]
        proj["bot"]["inherited_from"] = top.get("id")
    return proj


def critique_files(proj: dict) -> str:
    files = proj.get("files", [])
    total_lines = sum(len(f["content"].splitlines()) for f in files)
    eps = proj.get("app", {}).get("endpoints", [])
    notes = []
    if not any(f["path"].startswith("backend/") for f in files):
        notes.append("missing backend/ files — project will not run")
    if not any(f["path"] == "run.sh" for f in files):
        notes.append("no run.sh — onboarding will be painful")
    if not any(f["path"] == "README.md" for f in files):
        notes.append("no README — new contributors are lost")
    if total_lines < 100:
        notes.append(f"only {total_lines} lines of code — shape feels skeletal")
    if not any(ep.get("method") == "DELETE" for ep in eps):
        notes.append("no DELETE endpoint — destructive ops can't be undone via UI")
    if proj.get("bot", {}).get("domain") == "generic-crud":
        notes.append("fell back to generic CRUD — prompt may need clearer domain words")
    if not notes:
        notes = [
            f"{len(files)} files, {total_lines} loc — runnable footprint looks sound",
            f"{len(eps)} endpoints wired to the produced entities — good coverage",
            "consider swapping the in-memory dict for MongoDB before deploying",
        ]
    return " // ".join(notes[:3])


def rate_files(proj: dict) -> dict:
    files = proj.get("files", [])
    total_lines = sum(len(f["content"].splitlines()) for f in files)
    eps = proj.get("app", {}).get("endpoints", [])
    ents = proj.get("app", {}).get("entities", [])
    methods = {ep.get("method") for ep in eps}

    helpfulness = min(3.5, 1.0 + 0.4 * len(files))                 # more files → more helpful
    correctness = min(3.5, 0.8 + 0.3 * len(eps))                   # more endpoints wired
    coherence = 2.0 + (1.0 if {"GET", "POST"}.issubset(methods) else 0)
    coherence += 0.5 if {"PATCH", "DELETE"}.issubset(methods) else 0
    coherence = min(3.8, coherence)
    complexity = min(2.5, 0.5 + 0.2 * len(ents))
    verbosity = max(0.5, min(2.5, total_lines / 200.0))
    return {
        "helpfulness": round(helpfulness, 2),
        "correctness": round(correctness, 2),
        "coherence": round(coherence, 2),
        "complexity": round(complexity, 2),
        "verbosity": round(verbosity, 2),
    }
